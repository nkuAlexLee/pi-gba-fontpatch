function translateTask(task) {
  const parts = splitByTokens(task.en);
  const result = parts.map(p => {
    if (p.type === 'token') return p.value;
    return translateText(p.value);
  }).join('');
  return result;
}

function processBatch(inputPath, outputPath) {
  const data = JSON.parse(fs.readFileSync(inputPath, 'utf8'));
  const results = [];
  for (const task of data.tasks) {
    const zh = translateTask(task);
    results.push({ id: task.id, zh: zh });
  }
  fs.writeFileSync(outputPath, JSON.stringify(results, null, 1));
  return results.length;
}

