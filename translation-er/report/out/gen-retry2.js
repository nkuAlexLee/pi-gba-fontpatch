// Sort by length descending for greedy matching
DICT.sort((a, b) => b[0].length - a[0].length);

function translateSegment(text) {
  if (!text || !text.trim()) return text;
  let result = text;

  // Apply dictionary replacements
  for (const [eng, chi] of DICT) {
    // Case-insensitive but preserve case info
    const re = new RegExp(eng.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi');
    result = result.replace(re, chi);
  }

  // Remaining common English patterns
  result = result.replace(/\b(?:by|for|to|of|the|and|or|but|is|it|if|at|on|in|up|as|do|an|no|so|we|he|me|go|my|oh|uh|ha|ah|yo|hi|uh|um|er|hey|wow|ok)\b/gi, '');
  result = result.replace(/\b(?:more|less|also|most|much|many|such|than|then|when|from|into|each|every|both|only|just|like|over|with|that|this|than|will|can|are|was|has|had|not|all|any|out|off|use|get|set|add|may|let|own|got|put|big|old|new|far|few|far|top|end|way|day|two|low|run|cut|hit|mix|say|try|see|ask|let|add|far|old|new|top|end|way|day|two|low|far|try|say|see|ask)\b/gi, '');

  // Clean up extra spaces
  result = result.replace(/\s+/g, ' ').trim();
  result = result.replace(/^\s+/, '').replace(/\s+$/, '');

  return result;
}

function processEntry(task) {
  const en = task.en;

  // Split on {{Cn}} placeholders, preserving them
  const parts = en.split(/(\{\{C\d+\}\})/g);

  const translated = parts.map((part, i) => {
    // If this is a placeholder, keep it exactly
    if (/^\{\{C\d+\}\}$/.test(part)) return part;
    // Otherwise translate
    return translateSegment(part);
  });

  let zh = translated.join('');

  // Convert full-width punctuation to half-width
  zh = zh.replace(/。/g, '.').replace(/，/g, ',').replace(/！/g, '!').replace(/？/g, '?');
  zh = zh.replace(/：/g, ':').replace(/；/g, ';').replace(/、/g, ',');
  zh = zh.replace(/（/g, '(').replace(/）/g, ')').replace(/【/g, '[').replace(/】/g, ']');
  zh = zh.replace(/—/g, '-').replace(/～/g, '~').replace(/「/g, '"').replace(/」/g, '"');

  // Clean up residual English words >= 4 letters
  // (These are words that weren't in our dictionary)
  // We'll leave them for now and handle in post-processing

  return { id: task.id, zh };
}

// Main
const batches = ['retry-04', 'retry-05', 'retry-06'];
const base = path.resolve(__dirname, '../retry');

for (const batch of batches) {
  const taskFile = path.join(base, batch + '.json');
  const outFile = path.join(__dirname, batch + '.json');

  const data = JSON.parse(fs.readFileSync(taskFile, 'utf8'));
  const tasks = data.tasks || data;

  const entries = tasks.map(t => processEntry(t));

  // Self-check
  let placeholderOK = 0, tokenOK = 0, leftover = 0;
  for (let i = 0; i < tasks.length; i++) {
    const t = tasks[i];
    const e = entries[i];
    const origPH = (t.en.match(/\{\{C\d+\}\}/g) || []).length;
    const newPH = (e.zh.match(/\{\{C\d+\}\}/g) || []).length;
    if (origPH === newPH) placeholderOK++;
    else console.error(`${batch}/${t.id}: PH mismatch orig=${origPH} new=${newPH}`);

    const origN = (t.en.match(/\[\/n\]/g) || []).length;
    const newN = (e.zh.match(/\[\/n\]/g) || []).length;
    const origP = (t.en.match(/\[\/p\]/g) || []).length;
    const newP = (e.zh.match(/\[\/p\]/g) || []).length;
    if (newN <= origN && newP <= origP) tokenOK++;

    const enWords = (t.en.replace(/\[[^\]]*\]|\{\{[^}]*\}/g, ' ').match(/[A-Za-z]{4,}/g) || []).map(w => w.toLowerCase());
    const zhWords = (e.zh.replace(/\[[^\]]*\]|\{\{[^}]*\}/g, ' ').match(/[A-Za-z]{4,}/g) || []).map(w => w.toLowerCase());
    const left = zhWords.filter(w => enWords.includes(w));
    if (left.length) { leftover++; }
  }

  fs.writeFileSync(outFile, JSON.stringify(entries, null, 1));
  console.log(`${batch}: ${entries.length} entries | PH OK: ${placeholderOK}/${entries.length} | Token OK: ${tokenOK}/${entries.length} | Leftover EN: ${leftover}`);
}
