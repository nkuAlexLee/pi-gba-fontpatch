const outDir = 'D:/vibecoding/gba-font-cracker-js/gbajs2/translation-er/report/out';
const batchDir = 'D:/vibecoding/gba-font-cracker-js/gbajs2/translation-er/report/batches';

function writeBatch(num, map) {
  const tasks = JSON.parse(fs.readFileSync(batchDir + '/batch-' + String(num).padStart(3,'0') + '.json', 'utf8')).tasks;
  const out = tasks.map(t => ({ id: t.id, zh: map[t.id] || '' }));
  const f = outDir + '/batch-' + String(num).padStart(3,'0') + '.json';
  fs.writeFileSync(f, JSON.stringify(out, null, 2));
  
  // Self-check
  let issues = 0;
  for (const t of tasks) {
    const row = out.find(o => o.id === t.id);
    if (!row || !row.zh) { console.error('EMPTY:', t.id); issues++; continue; }
    const enP = (t.en.match(/\{\{C\d+\}\}/g) || []).length;
    const zhP = (row.zh.match(/\{\{C\d+\}\}/g) || []).length;
    if (enP !== zhP) {
      console.error('PLACEHOLDER MISMATCH:', t.id, 'en:', enP, 'zh:', zhP);
      issues++;
    }
  }
  console.log('batch', num, ':', out.length, 'items, issues:', issues);
}

